"""Regenerate docs/DATABASE.md (from SQLAlchemy metadata) and the endpoint index in docs/API.md (from OpenAPI).

Usage (from repo root): /path/to/venv/bin/python scripts/gen_docs.py
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api"))

from sqlalchemy.dialects import postgresql  # noqa: E402

from app.main import app  # noqa: E402
from app.models import Base, rls_tables  # noqa: E402

DOMAINS = {
    "identity.py": "Identity & sessions",
    "tenancy.py": "Organisations, RBAC & structure",
    "content.py": "Content & skills",
    "learning.py": "Learning progress",
    "assessment.py": "Assessments",
    "assignment.py": "Assignments & grading",
    "simulation.py": "Simulations",
    "ai.py": "AI & knowledge base",
    "platform.py": "Certificates, engagement, billing, audit & privacy",
}


def _type(col) -> str:  # noqa: ANN001
    try:
        t = col.type.compile(dialect=postgresql.dialect())
    except Exception:  # pragma: no cover
        t = col.type.__class__.__name__
    return t.lower().replace("timestamp with time zone", "timestamptz")


def database_md() -> str:
    rls = set(rls_tables())
    by_domain: dict[str, list] = defaultdict(list)
    for mapper in Base.registry.mappers:
        cls = mapper.class_
        by_domain[Path(sys.modules[cls.__module__].__file__).name].append(cls.__table__)
    for t in Base.metadata.tables.values():  # association tables
        if not any(t is x for xs in by_domain.values() for x in xs):
            by_domain["tenancy.py" if t.name in ("role_permissions", "membership_roles") else "content.py"].append(t)
    out = [
        "# Database",
        "",
        "PostgreSQL 16 + pgvector. Schema is managed by Alembic (`apps/api/alembic`). This file is generated by",
        "`scripts/gen_docs.py` from the SQLAlchemy models — do not edit by hand.",
        "",
        "## Conventions",
        "",
        "* UUID primary keys (`gen_random_uuid()`), `created_at` / `updated_at` (timestamptz) on every table,",
        "  `deleted_at` soft delete on user-facing content.",
        "* Every tenant-scoped table has an indexed `organisation_id` and a **row-level security** policy",
        "  (`tenant_isolation`, `FORCE ROW LEVEL SECURITY`) keyed on the transaction-local `app.org_id` setting.",
        "  Tables marked 🔒 below are RLS-protected.",
        "* Versioning: `course_versions.snapshot` (immutable published course tree), `simulation_scenarios`",
        "  (versioned definitions), `submission_versions`, frozen `assessment_attempts.questions_snapshot`, and",
        "  append-only `grades`, so historical results never change when content changes.",
        "* `audit_logs` is append-only (UPDATE/DELETE/TRUNCATE blocked by triggers) and hash-chained per organisation.",
        "* Vector search: `knowledge_chunks.embedding vector(1536)` with an HNSW cosine index.",
        "",
        f"**{len(Base.metadata.tables)} tables, {len(rls)} under RLS.** See the ERD in [ARCHITECTURE.md](./ARCHITECTURE.md#3-database-erd).",
        "",
    ]
    for fname, title in DOMAINS.items():
        tables = sorted(by_domain.get(fname, []), key=lambda t: t.name)
        if not tables:
            continue
        out += [f"## {title}", ""]
        for t in tables:
            lock = " 🔒" if t.name in rls else ""
            out += [f"### `{t.name}`{lock}", ""]
            doc = None
            for mapper in Base.registry.mappers:
                if mapper.class_.__table__ is t and mapper.class_.__doc__:
                    doc = " ".join(mapper.class_.__doc__.split())
            if doc:
                out += [doc, ""]
            out += ["| Column | Type | Null | Key / default |", "|---|---|---|---|"]
            for c in t.columns:
                keys = []
                if c.primary_key:
                    keys.append("PK")
                for fk in c.foreign_keys:
                    keys.append(f"→ `{fk.target_fullname}`" + (f" ({fk.ondelete})" if fk.ondelete else ""))
                if c.unique:
                    keys.append("unique")
                if c.index:
                    keys.append("indexed")
                out.append(f"| `{c.name}` | {_type(c)} | {'yes' if c.nullable else 'no'} | {', '.join(keys)} |")
            extra = [
                f"unique({', '.join(col.name for col in con.columns)})"
                for con in t.constraints
                if con.__class__.__name__ == "UniqueConstraint" and len(con.columns) > 1
            ]
            extra += [
                f"index `{ix.name}` ({', '.join(col.name for col in ix.columns)})"
                for ix in t.indexes
                if len(ix.columns) > 1 or ix.name.endswith("_hnsw")
            ]
            if extra:
                out += ["", "Constraints / indexes: " + "; ".join(extra)]
            out.append("")
    return "\n".join(out)


def api_index_md() -> str:
    spec = app.openapi()
    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            groups[tag].append((method.upper(), path, op.get("summary", "")))
    lines = [f"_{sum(len(v) for v in groups.values())} operations across {len(groups)} groups (generated)._", ""]
    for tag in sorted(groups):
        lines += [f"### {tag}", "", "| Method | Path | Summary |", "|---|---|---|"]
        for m, p, s in sorted(groups[tag], key=lambda x: (x[1], x[0])):
            lines.append(f"| `{m}` | `{p}` | {s} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    (ROOT / "docs" / "DATABASE.md").write_text(database_md())
    api = ROOT / "docs" / "API.md"
    if api.exists():
        text = api.read_text()
        new = re.sub(
            r"<!-- endpoint-index:start -->.*?<!-- endpoint-index:end -->",
            lambda m: "<!-- endpoint-index:start -->\n" + api_index_md() + "\n<!-- endpoint-index:end -->",
            text,
            flags=re.S,
        )
        api.write_text(new)
    print("docs regenerated")


if __name__ == "__main__":
    main()
